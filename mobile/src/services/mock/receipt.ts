import { NativeModules } from 'react-native';
import type { Order } from '../../types/preview';

export function receiptLines(order: Order, tenant: string) {
  return ['NaSCon Sports — MOCK PAYMENT RECEIPT',tenant,`Order: ${order.order_id}`,`Status: ${order.status}`,`Paid: ${order.paid_at||order.created_at||'Not recorded'}`,'',
    ...order.items.map(x=>`${x.name||x.variant_id} | ${x.quantity} x PKR ${(x.unit_price_minor/100).toFixed(2)}`),'',
    `Subtotal: PKR ${(order.subtotal_minor/100).toFixed(2)}`,`Discount: PKR ${(order.discount_minor/100).toFixed(2)}`,`Total: PKR ${(order.total_minor/100).toFixed(2)}`,'',
    'Generated by the local mock application. No real payment was made.'];
}
export async function exportReceipt(order: Order, tenant: string, download: boolean) {
  if(!NativeModules.NaSConReceipt)throw new Error('Rebuild the Android app to enable receipt PDF export.');
  const filename=`nascon-${order.order_id.replace(/[^a-z0-9_-]/gi,'_')}.pdf`;
  return NativeModules.NaSConReceipt.exportReceipt(receiptLines(order,tenant),filename,download) as Promise<string>;
}
